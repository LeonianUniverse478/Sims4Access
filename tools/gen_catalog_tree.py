"""Generate Scripts/tyjokr_a11y_catalogtree.py: EA's Buy catalog tree.

    python tools/gen_catalog_tree.py <BuildBuyNavigation export> <BuildBuyLibrary export>

The arguments are FFDec script exports (`-export script`) of the game's
BuildBuyNavigation and BuildBuyLibrary movies. The tree is what the Buy panel
shows: by room (CatalogData.ROOM_CATEGORIES) and by function
(CatalogData.BUY_CATEGORIES), each with the FilterButtons of its panel
(BuildBuy/Navigation/<Panel>.as) in declaration order. Every label is the
string hash of the KeysBB or Keys constant EA uses, so the game shows it in
the player's language; the English comment is for readers only.
"""
import re
import sys
from pathlib import Path

ROOM_PANELS = {'kitchen': 'Kitchen', 'bath': 'Bathroom', 'bed': 'Bedroom', 'living': 'LivingRoom',
               'dining': 'Diningroom', 'study': 'Study', 'kids': 'KidsRoom', 'outdoor': 'Outdoor'}
FUNCTION_PANELS = {'comfort': 'Func_Comfort', 'surfaces': 'Func_Surfaces', 'plumbing': 'Func_Plumbing',
                   'entertainment': 'Func_Entertainment', 'decorations': 'Func_Decorations', 'kids': 'Func_Kids',
                   'lighting': 'Func_Lighting', 'electronics': 'Func_Electronics', 'appliances': 'Func_Appliances',
                   'storage': 'Func_Storage', 'offthegrid': 'Func_OffTheGrid', 'waterfeatures': 'Func_WaterFeatures',
                   'pets': 'Func_Pets'}


def read(path):
    return Path(path).read_text(encoding='utf-8')


def main():
    nav, lib = Path(sys.argv[1]) / 'scripts', Path(sys.argv[2]) / 'scripts'
    hashes = {}
    for cls in ('KeysBB', 'Keys'):
        text = read(next(lib.rglob(cls + '.as')))
        for name, value in re.findall(r'const (\w+):LocKey = LocKey\.FromHash\((\d+)\)', text):
            hashes[cls + '.' + name] = int(value)
    tooltips = dict(re.findall(r'const (\w+):String = ((?:Keys|KeysBB)\.\w+)\.toString\(\)',
                               read(next(nav.rglob('FilterTooltips.as')))))
    types = {n: int(v) for n, v in re.findall(r'const (\w+):int = (\d+);', read(next(nav.rglob('ProductTypes.as'))))}
    data = read(next(nav.rglob('CatalogData.as')))
    body = data[data.index('public static function Create'):]

    def top(list_name, panels):
        start = re.search(r'\b' + list_name + r' = (?:new|\[)', body).start()
        end = body.index(';', start)
        items = re.findall(r'new MenuItem\(((?:Keys|KeysBB)\.\w+)\.toString\(\),\{\s*"frameLabel":"(\w+)"', body[start:end])
        # Pack-only categories are spliced in at run time (Pets with Cats & Dogs);
        # they are listed too, and simply come up empty without the pack.
        items += re.findall(r'\b' + list_name + r'\.splice\(\w+,0,new MenuItem\(((?:Keys|KeysBB)\.\w+)\.toString\(\),\{\s*"frameLabel":"(\w+)"', body)
        return [(key, panels[frame]) for key, frame in items if frame in panels]

    def panel(name):
        text = read(nav / 'BuildBuy' / 'Navigation' / (name + '.as'))
        order = re.findall(r'public var (__id\d+_):', text)
        rows = []
        for ident in order:
            props = dict(re.findall(r'this\.' + ident + r'\.(\w+) = "?([^";]*)"?;', text))
            label = tooltips.get(props.get('TooltipText', ''))
            if not label or label not in hashes or props.get('DebugOnly') == 'true':
                continue
            rows.append((hashes[label], types.get(props.get('ProductType', 'OBJECT'), 2),
                         props.get('CategoryTags', ''), props.get('CategoryTagsPriority', ''), label))
        return rows

    english = {}
    out = ['"""EA\'s Buy catalog tree: by room and by function.', '',
           'GENERATED by tools/gen_catalog_tree.py from the game\'s BuildBuyNavigation',
           'and BuildBuyLibrary movies; do not edit by hand. Labels are string hashes',
           'the game resolves in the player\'s language; the trailing comment names the',
           'EA key, for readers only. Rows: (label hash, product type, category tags,',
           'priority tags).', '"""', '']
    for var, list_name, panels in (('ROOMS', 'ROOM_CATEGORIES', ROOM_PANELS),
                                   ('FUNCTIONS', 'BUY_CATEGORIES', FUNCTION_PANELS)):
        out.append(var + ' = (')
        seen = set()
        for key, name in top(list_name, panels):
            if name in seen:
                continue
            seen.add(name)
            rows = panel(name)
            out.append('    (0x%08X, (  # %s' % (hashes[key], key))
            for h, t, tags, pri, label in rows:
                out.append('        (0x%08X, %d, %r, %r),  # %s' % (h, t, tags, pri, label))
            out.append('    )),')
        out.append(')')
        out.append('')
    target = Path(__file__).resolve().parents[1] / 'Scripts' / 'tyjokr_a11y_catalogtree.py'
    target.write_text('\n'.join(out), encoding='utf-8')
    print('wrote', target)


if __name__ == '__main__':
    main()
